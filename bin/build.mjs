#!/usr/bin/env node
// Compiles tokens/platinum.tokens.json + src/*.css into zero-dependency dist/*.css bundles.
// Usage:
//   node bin/build.mjs          # write dist/*.css
//   node bin/build.mjs --check  # verify dist/*.css are byte-for-byte up to date (zero writes)

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function emitVars(obj, prefix = "--pt-") {
  const lines = [];
  for (const [key, entry] of Object.entries(obj)) {
    if (key.startsWith("$")) continue;
    lines.push(`    ${prefix}${key}: ${entry.$value};`);
  }
  return lines.join("\n");
}

export function compileTokensCss(tokens, { scopedOnly = false } = {}) {
  const hostSel = scopedOnly ? "[data-platinum]" : ":root, [data-platinum]";
  const darkHostAuto = scopedOnly
    ? '[data-platinum]:not([data-platinum-scheme="light"], [data-theme="platinum-light"])'
    : ':root:not([data-platinum-scheme="light"], [data-theme="platinum-light"]), [data-platinum]:not([data-platinum-scheme="light"], [data-theme="platinum-light"])';
  const forceLightSel = '[data-platinum-scheme="light"], [data-theme="platinum-light"]';
  const forceDarkSel = '[data-platinum-scheme="dark"], [data-theme="platinum-dark"]';
  const lavLightSel = '[data-platinum-accent="lavender"]';
  const lavAutoDarkSel = '[data-platinum-accent="lavender"]:not([data-platinum-scheme="light"], [data-theme="platinum-light"])';
  const lavForceDarkSel = ':is([data-platinum-scheme="dark"], [data-theme="platinum-dark"])[data-platinum-accent="lavender"], [data-platinum-scheme="dark"] [data-platinum-accent="lavender"], [data-platinum-accent="lavender"] [data-platinum-scheme="dark"]';
  const lavForceLightSel = ':is([data-platinum-scheme="light"], [data-theme="platinum-light"])[data-platinum-accent="lavender"], [data-platinum-scheme="light"] [data-platinum-accent="lavender"]';
  const comfortableSel = '[data-platinum-density="comfortable"]';

  return `/* Generated by platinum-ui bin/build.mjs from tokens/platinum.tokens.json — DO NOT HAND-EDIT */
@layer pt.tokens, pt.core, pt.elements, pt.prose;

@layer pt.tokens {
  ${hostSel} {
    color-scheme: light dark;
${emitVars(tokens.typography)}
${emitVars(tokens.radius, "--pt-radius-")}
${emitVars(tokens.space, "--pt-space-")}
${emitVars(tokens.density.compact)}
${emitVars(tokens.chassis.light)}
${emitVars(tokens.variants.gray.light)}
  }

  @media (prefers-color-scheme: dark) {
    ${darkHostAuto} {
${emitVars(tokens.chassis.dark)}
${emitVars(tokens.variants.gray.dark)}
    }
    ${lavAutoDarkSel} {
${emitVars(tokens.variants.lavender.dark)}
    }
  }

  ${forceLightSel} {
    color-scheme: light;
${emitVars(tokens.chassis.light)}
${emitVars(tokens.variants.gray.light)}
  }

  ${forceDarkSel} {
    color-scheme: dark;
${emitVars(tokens.chassis.dark)}
${emitVars(tokens.variants.gray.dark)}
  }

  ${lavLightSel} {
${emitVars(tokens.variants.lavender.light)}
  }

  ${lavForceLightSel} {
${emitVars(tokens.variants.lavender.light)}
  }

  ${lavForceDarkSel} {
${emitVars(tokens.variants.lavender.dark)}
  }

  ${comfortableSel} {
${emitVars(tokens.density.comfortable)}
  }
}
`;
}

function compileElementsCss(rawElements, { scopedOnly = false } = {}) {
  if (scopedOnly) {
    return rawElements
      .replaceAll("__PT_ROOT__", "[data-platinum]")
      .replaceAll("__PT_SCOPE__", "[data-platinum]");
  }
  return rawElements
    .replaceAll("__PT_ROOT__", ":is(:root, body)")
    .replaceAll("__PT_SCOPE__", ":is(:root, body)");
}

export function buildAllBundles(root = ROOT) {
  const tokens = JSON.parse(readFileSync(join(root, "tokens/platinum.tokens.json"), "utf8"));
  const coreCss = readFileSync(join(root, "src/core.css"), "utf8");
  const rawElements = readFileSync(join(root, "src/elements.css"), "utf8");
  const proseCss = readFileSync(join(root, "src/prose.css"), "utf8");

  const globalTokens = compileTokensCss(tokens, { scopedOnly: false });
  const scopedTokens = compileTokensCss(tokens, { scopedOnly: true });
  const globalElements = compileElementsCss(rawElements, { scopedOnly: false });
  const scopedElements = compileElementsCss(rawElements, { scopedOnly: true });

  return {
    "dist/platinum-tokens.css": globalTokens,
    "dist/platinum-core.css": `${globalTokens}\n${coreCss}\n${proseCss}`,
    "dist/platinum.css": `${globalTokens}\n${coreCss}\n${globalElements}\n${proseCss}`,
    "dist/platinum-scoped.css": `${scopedTokens}\n${coreCss}\n${scopedElements}\n${proseCss}`
  };
}

function main() {
  const checkOnly = process.argv.includes("--check");
  const bundles = buildAllBundles(ROOT);
  const drifted = [];

  if (!checkOnly) {
    mkdirSync(join(ROOT, "dist"), { recursive: true });
  }

  for (const [relPath, expected] of Object.entries(bundles)) {
    const abs = join(ROOT, relPath);
    if (checkOnly) {
      if (!existsSync(abs) || readFileSync(abs, "utf8") !== expected) {
        drifted.push(relPath);
      }
    } else {
      writeFileSync(abs, expected, "utf8");
    }
  }

  if (checkOnly) {
    if (drifted.length > 0) {
      console.error(`[platinum-build] DRIFT DETECTED in: ${drifted.join(", ")}. Run: npm run build`);
      process.exit(1);
    }
    console.log(`[platinum-build] OK — ${Object.keys(bundles).length} dist bundles byte-exact`);
  } else {
    console.log(`[platinum-build] Wrote ${Object.keys(bundles).length} bundles to dist/`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
