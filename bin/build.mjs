#!/usr/bin/env node
// Compiles tokens/platinum.tokens.json + src/*.css into zero-dependency dist/*.css bundles.
// Usage:
//   node bin/build.mjs          # write dist/*.css
//   node bin/build.mjs --check  # verify dist/*.css are byte-for-byte up to date (zero writes)

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function emitVars(obj, prefix = "--pt-", indent = "    ") {
  const lines = [];
  for (const [key, entry] of Object.entries(obj)) {
    if (key.startsWith("$")) continue;
    lines.push(`${indent}${prefix}${key}: ${entry.$value};`);
  }
  return lines.join("\n");
}

function emitVariantSlots(variant, indent = "    ") {
  const lines = [];
  for (const key of Object.keys(variant.light)) {
    if (key.startsWith("$")) continue;
    lines.push(`${indent}--_pt-l-${key}: ${variant.light[key].$value};`);
    lines.push(`${indent}--_pt-d-${key}: ${variant.dark[key].$value};`);
  }
  return lines.join("\n");
}

function bindVariantSlots(variantKeys, modePrefix, scrollbarTokens, indent = "      ") {
  const lines = [];
  for (const key of variantKeys) {
    lines.push(`${indent}--pt-${key}: var(--_pt-${modePrefix}-${key});`);
  }
  lines.push(emitVars(scrollbarTokens, "--pt-", indent));
  return lines.join("\n");
}

export function compileTokensCss(tokens, { scopedOnly = false } = {}) {
  const mountGuard = scopedOnly ? ":where([data-platinum], [data-platinum] *)" : "";
  // Outermost mount only: nested [data-platinum] containers inherit parent scheme/accent/density unless explicitly set
  const hostSel = scopedOnly
    ? ":where([data-platinum]:not([data-platinum] *))"
    : ":where(:root)";
  const forceLightBase = '[data-platinum-scheme="light"], [data-theme="platinum-light"]';
  const forceDarkBase = '[data-platinum-scheme="dark"], [data-theme="platinum-dark"]';
  const schemeBoundary = `${forceLightBase}, ${forceDarkBase}`;
  const darkHostAuto = scopedOnly
    ? `:where([data-platinum]:not([data-platinum] *)):not(${schemeBoundary})`
    : `:where(:root):not(${schemeBoundary})`;
  const forceLightScope = scopedOnly
    ? `:is(${forceLightBase})${mountGuard}`
    : `:where(${forceLightBase})`;
  const forceDarkScope = scopedOnly
    ? `:is(${forceDarkBase})${mountGuard}`
    : `:where(${forceDarkBase})`;
  const graySel = `:where([data-platinum-accent="gray"])${mountGuard}`;
  const lavSel = `:where([data-platinum-accent="lavender"])${mountGuard}`;
  const compactSel = `:where([data-platinum-density="compact"])${mountGuard}`;
  const comfortableSel = `:where([data-platinum-density="comfortable"])${mountGuard}`;
  const rebindTargets = `:where(:scope, [data-platinum-accent="gray"], [data-platinum-accent="lavender"])${mountGuard}`;

  const variantKeys = Object.keys(tokens.variants.gray.light).filter((k) => !k.startsWith("$"));

  return `/* Generated by platinum-ui bin/build.mjs from tokens/platinum.tokens.json — DO NOT HAND-EDIT */
@layer pt.tokens, pt.core, pt.elements, pt.prose;

@layer pt.tokens {
  ${hostSel} {
    color-scheme: light dark;
${emitVars(tokens.typography)}
${emitVars(tokens.radius, "--pt-radius-")}
${emitVars(tokens.space, "--pt-space-")}
${emitVars(tokens.density.compact)}
${emitVariantSlots(tokens.variants.gray)}
${emitVars(tokens.chassis.light)}
${bindVariantSlots(variantKeys, "l", tokens.scrollbar, "    ")}
  }

  ${graySel} {
${emitVariantSlots(tokens.variants.gray)}
${bindVariantSlots(variantKeys, "l", tokens.scrollbar, "    ")}
  }

  ${lavSel} {
${emitVariantSlots(tokens.variants.lavender)}
${bindVariantSlots(variantKeys, "l", tokens.scrollbar, "    ")}
  }

  /* Single-layer fallback for engines without @scope, refined by @scope below for arbitrary nesting */
  @media (prefers-color-scheme: dark) {
    ${darkHostAuto} {
${emitVars(tokens.chassis.dark, "--pt-", "      ")}
${bindVariantSlots(variantKeys, "d", tokens.scrollbar, "      ")}
    }
    @scope (${darkHostAuto}) to (${schemeBoundary}) {
      :where(:scope)${mountGuard} {
${emitVars(tokens.chassis.dark, "--pt-", "        ")}
      }
      ${rebindTargets} {
${bindVariantSlots(variantKeys, "d", tokens.scrollbar, "        ")}
      }
    }
  }

  ${forceLightScope} {
    color-scheme: light;
${emitVars(tokens.chassis.light)}
${bindVariantSlots(variantKeys, "l", tokens.scrollbar, "    ")}
  }

  ${forceDarkScope} {
    color-scheme: dark;
${emitVars(tokens.chassis.dark)}
${bindVariantSlots(variantKeys, "d", tokens.scrollbar, "    ")}
  }

  @scope (${forceLightScope}) to (${schemeBoundary}) {
    :where(:scope) {
      color-scheme: light;
${emitVars(tokens.chassis.light, "--pt-", "      ")}
    }
    ${rebindTargets} {
${bindVariantSlots(variantKeys, "l", tokens.scrollbar, "      ")}
    }
  }

  @scope (${forceDarkScope}) to (${schemeBoundary}) {
    :where(:scope) {
      color-scheme: dark;
${emitVars(tokens.chassis.dark, "--pt-", "      ")}
    }
    ${rebindTargets} {
${bindVariantSlots(variantKeys, "d", tokens.scrollbar, "      ")}
    }
  }

  ${compactSel} {
${emitVars(tokens.density.compact)}
  }

  ${comfortableSel} {
${emitVars(tokens.density.comfortable)}
  }
}
`;
}

function splitTopSelectors(selectorList) {
  const parts = [];
  let start = 0;
  let paren = 0;
  let bracket = 0;
  let inStr = null;
  for (let i = 0; i < selectorList.length; i++) {
    const ch = selectorList[i];
    if (inStr) {
      if (ch === "\\") i++;
      else if (ch === inStr) inStr = null;
    } else if (ch === '"' || ch === "'") {
      inStr = ch;
    } else if (ch === "(") {
      paren++;
    } else if (ch === ")") {
      paren = Math.max(0, paren - 1);
    } else if (ch === "[") {
      bracket++;
    } else if (ch === "]") {
      bracket = Math.max(0, bracket - 1);
    } else if (ch === "," && paren === 0 && bracket === 0) {
      parts.push(selectorList.slice(start, i).trim());
      start = i + 1;
    }
  }
  parts.push(selectorList.slice(start).trim());
  return parts.filter(Boolean);
}

function findTopPseudoElementIndex(sel) {
  let paren = 0;
  let bracket = 0;
  let inStr = null;
  for (let i = 0; i < sel.length - 1; i++) {
    const ch = sel[i];
    if (inStr) {
      if (ch === "\\") i++;
      else if (ch === inStr) inStr = null;
    } else if (ch === '"' || ch === "'") {
      inStr = ch;
    } else if (ch === "(") {
      paren++;
    } else if (ch === ")") {
      paren = Math.max(0, paren - 1);
    } else if (ch === "[") {
      bracket++;
    } else if (ch === "]") {
      bracket = Math.max(0, bracket - 1);
    } else if (paren === 0 && bracket === 0 && ch === ":" && sel[i + 1] === ":") {
      return i;
    }
  }
  return -1;
}

function findFirstTopCombinatorIndex(sel) {
  let paren = 0;
  let bracket = 0;
  let inStr = null;
  for (let i = 0; i < sel.length; i++) {
    const ch = sel[i];
    if (inStr) {
      if (ch === "\\") i++;
      else if (ch === inStr) inStr = null;
    } else if (ch === '"' || ch === "'") {
      inStr = ch;
    } else if (ch === "(") {
      paren++;
    } else if (ch === ")") {
      paren = Math.max(0, paren - 1);
    } else if (ch === "[") {
      bracket++;
    } else if (ch === "]") {
      bracket = Math.max(0, bracket - 1);
    } else if (paren === 0 && bracket === 0 && (ch === ">" || ch === "+" || ch === "~" || /\s/.test(ch))) {
      return i;
    }
  }
  return -1;
}

function guardRightmostSelector(sel, guard) {
  const pIdx = findTopPseudoElementIndex(sel);
  if (pIdx < 0) {
    return `${sel}${guard}`;
  }
  const elemPart = sel.slice(0, pIdx);
  const pseudoPart = sel.slice(pIdx);
  if (!elemPart || /[\s>+~]$/.test(elemPart)) {
    return `${elemPart}*${guard}${pseudoPart}`;
  }
  return `${elemPart}${guard}${pseudoPart}`;
}

function scopeSingleSelector(sel) {
  const guard = ":where([data-platinum], [data-platinum] *)";
  if (sel.includes("[data-platinum]")) return sel;
  const cIdx = findFirstTopCombinatorIndex(sel);
  if (cIdx > 0) {
    const leftPart = sel.slice(0, cIdx);
    const restPart = sel.slice(cIdx);
    return `${leftPart}${guard}${guardRightmostSelector(restPart, guard)}`;
  }
  return guardRightmostSelector(sel, guard);
}

export function scopeCssLayerRules(cssText) {
  const transformBlock = (src) => {
    let out = "";
    let i = 0;
    while (i < src.length) {
      const wsStart = i;
      while (i < src.length && /\s/.test(src[i])) i++;
      out += src.slice(wsStart, i);
      if (i >= src.length) break;

      if (src.startsWith("/*", i)) {
        const endComment = src.indexOf("*/", i + 2);
        const stop = endComment < 0 ? src.length : endComment + 2;
        out += src.slice(i, stop);
        i = stop;
        continue;
      }

      const headStart = i;
      let paren = 0;
      let bracket = 0;
      let inStr = null;
      while (i < src.length) {
        const ch = src[i];
        if (inStr) {
          if (ch === "\\") i++;
          else if (ch === inStr) inStr = null;
        } else if (ch === '"' || ch === "'") {
          inStr = ch;
        } else if (ch === "(") {
          paren++;
        } else if (ch === ")") {
          paren = Math.max(0, paren - 1);
        } else if (ch === "[") {
          bracket++;
        } else if (ch === "]") {
          bracket = Math.max(0, bracket - 1);
        } else if (paren === 0 && bracket === 0 && (ch === "{" || ch === ";")) {
          break;
        }
        i++;
      }
      if (i >= src.length) {
        out += src.slice(headStart);
        break;
      }
      const head = src.slice(headStart, i).trim();
      if (src[i] === ";") {
        out += src.slice(headStart, i + 1);
        i++;
        continue;
      }

      const bodyStart = i + 1;
      let depth = 1;
      i++;
      inStr = null;
      while (i < src.length && depth > 0) {
        const ch = src[i];
        if (inStr) {
          if (ch === "\\") i++;
          else if (ch === inStr) inStr = null;
        } else if (ch === '"' || ch === "'") {
          inStr = ch;
        } else if (src.startsWith("/*", i)) {
          const endC = src.indexOf("*/", i + 2);
          i = endC < 0 ? src.length : endC + 1;
        } else if (ch === "{") {
          depth++;
        } else if (ch === "}") {
          depth--;
        }
        i++;
      }
      const body = src.slice(bodyStart, i - 1);

      if (head.startsWith("@")) {
        if (/^@scope\s*\(([\s\S]*)\)\s*(to\s*\([\s\S]*\))?$/.test(head)) {
          const m = /^@scope\s*\(([\s\S]*?)\)(\s*to\s*\([\s\S]*\))?$/.exec(head);
          if (m) {
            const scopedRoots = splitTopSelectors(m[1]).map(scopeSingleSelector).join(", ");
            out += `@scope (${scopedRoots})${m[2] || ""} {${body}}`;
          } else {
            out += `${head} {${body}}`;
          }
        } else if (/^@(?:font-face|keyframes|property)\b/.test(head)) {
          out += `${head} {${body}}`;
        } else {
          out += `${head} {${transformBlock(body)}}`;
        }
      } else {
        const scopedHead = splitTopSelectors(head).map(scopeSingleSelector).join(",\n  ");
        out += `${scopedHead} {${body}}`;
      }
    }
    return out;
  };
  return transformBlock(cssText);
}

function compileElementsCss(rawElements, { scopedOnly = false } = {}) {
  if (scopedOnly) {
    const unprefixed = rawElements
      .replaceAll("__PT_ROOT__", "[data-platinum]")
      .replaceAll("__PT_SCOPE__ ", "")
      .replaceAll("__PT_SCOPE__", "[data-platinum]")
      .replaceAll("__PT_SCROLL_SCOPE__ ", "[data-platinum] ")
      .replaceAll("__PT_SCROLL_SCOPE__", "[data-platinum]");
    return scopeCssLayerRules(unprefixed);
  }
  const scope = ":is(:root, body)";
  // Blink misses scrollbar orientation selectors under :is(:root, body).
  const scrollScope = "html";
  return rawElements
    .replaceAll("__PT_ROOT__", scope)
    .replaceAll("__PT_SCOPE__", scope)
    .replaceAll("__PT_SCROLL_SCOPE__", scrollScope);
}

export function buildAllBundles(root = ROOT) {
  const tokens = JSON.parse(readFileSync(join(root, "tokens/platinum.tokens.json"), "utf8"));
  const coreCss = readFileSync(join(root, "src/core.css"), "utf8");
  const rawElements = readFileSync(join(root, "src/elements.css"), "utf8");
  const proseCss = readFileSync(join(root, "src/prose.css"), "utf8");

  const globalTokens = compileTokensCss(tokens, { scopedOnly: false });
  const scopedTokens = compileTokensCss(tokens, { scopedOnly: true });
  const globalElements = compileElementsCss(rawElements, { scopedOnly: false });
  const scopedElements = compileElementsCss(rawElements, { scopedOnly: true });
  const scopedCore = scopeCssLayerRules(coreCss);
  const scopedProse = scopeCssLayerRules(proseCss);

  return {
    "dist/platinum-tokens.css": globalTokens,
    "dist/platinum-core.css": `${globalTokens}\n${coreCss}\n${proseCss}`,
    "dist/platinum.css": `${globalTokens}\n${coreCss}\n${globalElements}\n${proseCss}`,
    "dist/platinum-scoped.css": `${scopedTokens}\n${scopedCore}\n${scopedElements}\n${scopedProse}`
  };
}

function main() {
  const checkOnly = process.argv.includes("--check");
  const bundles = buildAllBundles(ROOT);
  const drifted = [];

  if (!checkOnly) {
    mkdirSync(join(ROOT, "dist"), { recursive: true });
  }

  for (const [relPath, expected] of Object.entries(bundles)) {
    const abs = join(ROOT, relPath);
    if (checkOnly) {
      if (!existsSync(abs) || readFileSync(abs, "utf8") !== expected) {
        drifted.push(relPath);
      }
    } else {
      writeFileSync(abs, expected, "utf8");
    }
  }

  if (checkOnly) {
    if (drifted.length > 0) {
      console.error(`[platinum-build] DRIFT DETECTED in: ${drifted.join(", ")}. Run: npm run build`);
      process.exit(1);
    }
    console.log(`[platinum-build] OK — ${Object.keys(bundles).length} dist bundles byte-exact`);
  } else {
    console.log(`[platinum-build] Wrote ${Object.keys(bundles).length} bundles to dist/`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
