import assert from 'node:assert/strict';
import { before, after, describe, it } from 'node:test';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { resolvePlaywright } from '../bin/platinum-check.mjs';
import {
  loadSamples, readReference, referenceRoot, captureSample,
  compareImages, strictFailures, sourceDigest, sha256
} from '../scripts/reference-lib.mjs';

// Dark, neutral ink excludes the gray title ridges and colored proxy icon.
// These regions stay inside the text's flat background, away from window rules.
async function textInk(browser, png, region) {
  const page = await browser.newPage();
  try {
    return await page.evaluate(async ({ base64, region }) => {
      const image = new Image();
      image.src = 'data:image/png;base64,' + base64;
      await image.decode();
      const canvas = document.createElement('canvas');
      canvas.width = region.width;
      canvas.height = region.height;
      const context = canvas.getContext('2d');
      context.drawImage(image, region.x, region.y, region.width, region.height,
        0, 0, region.width, region.height);
      const pixels = context.getImageData(0, 0, region.width, region.height).data;
      let left = region.width, right = -1, top = region.height, bottom = -1, count = 0;
      for (let y = 0; y < region.height; y++) {
        for (let x = 0; x < region.width; x++) {
          const index = (y * region.width + x) * 4;
          const channels = [pixels[index], pixels[index + 1], pixels[index + 2]];
          if (Math.max(...channels) < 96
              && Math.max(...channels) - Math.min(...channels) < 20
              && pixels[index + 3] > 240) {
            left = Math.min(left, x);
            right = Math.max(right, x);
            top = Math.min(top, y);
            bottom = Math.max(bottom, y);
            count++;
          }
        }
      }
      return { count, width: right - left + 1, height: bottom - top + 1,
        centerX: (left + right) / 2, center: (top + bottom) / 2 };
    }, { base64: png.toString('base64'), region });
  } finally {
    await page.close();
  }
}

const playwright = resolvePlaywright();
const ci = Boolean(process.env.CI);
describe('Historical window screenshots at DPR 1', {
  skip: !playwright && !ci && 'Playwright unavailable: reference screenshot checks require an installed browser'
}, () => {
  let browser, manifest;
  before(async () => {
    assert.ok(playwright, 'CI requires Playwright for historical reference checks');
    manifest = loadSamples();
    try {
      browser = await playwright.chromium.launch({ ignoreDefaultArgs: ['--hide-scrollbars'] });
    } catch (error) {
      throw new Error(`Historical reference browser cannot launch. Install the configured Chromium browser before running this gate. ${error.message}`);
    }
  });
  after(async () => browser?.close());

  it('keeps the file:// manifest mirror and source provenance current', async () => {
    const mirror = readReference('samples.js').toString();
    assert.equal(mirror, `// Generated by scripts/reference-shots.mjs; source: samples.json\nwindow.PLATINUM_REFERENCE = ${readReference('samples.json').toString().trimEnd()};\n`);
    const previews = JSON.parse(readReference('previews.json'));
    assert.equal(previews.sourceDigest, sourceDigest(), 'Preview inputs changed; run node scripts/reference-shots.mjs');
    assert.deepEqual(previews.reports.map(report => report.id), manifest.samples.map(sample => sample.id));
  });

  it('verifies saved full differences and reports against committed pixels without rerasterizing fonts', async () => {
    const previews = JSON.parse(readReference('previews.json'));
    for (const sample of manifest.samples) {
      const saved = previews.reports.find(report => report.id === sample.id);
      const files = Object.fromEntries(['original', 'rendered', 'difference', 'capture'].map(directory => {
        return [directory, readReference(`${directory}/${sample.id}.png`)];
      }));
      assert.deepEqual(saved.hashes, Object.fromEntries(Object.entries(files).map(([name, bytes]) => {
        return [name, sha256(bytes)];
      })), `${sample.id}: saved artifact hash changed`);
      const recomputed = await compareImages(browser, files.original, files.rendered, sample.regions);
      const { png, ...metrics } = recomputed;
      const { id, hashes, ...savedMetrics } = saved;
      assert.deepEqual(savedMetrics, metrics, `${sample.id}: saved report differs from committed images`);
      const difference = await compareImages(browser, files.difference, Buffer.from(png, 'base64'));
      assert.equal(difference.absoluteError, 0, `${sample.id}: saved difference PNG is incorrect`);
    }
  });

  it('proves every historical original is an exact RGBA crop of its captured guest frame', async () => {
    for (const sample of manifest.samples) {
      const frame = readReference(`capture/${sample.id}.png`);
      const original = readReference(`original/${sample.id}.png`);
      const report = await compareImages(browser, frame, original, [], sample.crop);
      assert.equal(report.changed, 0, `${sample.id}: original differs from the captured guest-frame crop`);
      assert.equal(report.absoluteError, 0, `${sample.id}: crop RGBA bytes differ`);
    }
  });

  it('compares real current screenshots against every named historical region', async () => {
    for (const sample of manifest.samples) {
      assert.ok(sample.regions?.some(region => region.mode !== 'review' && !region.review), `${sample.id}: no strict historical regions`);
      const actual = await captureSample(browser, sample);
      const historical = readReference(`original/${sample.id}.png`);
      const comparison = await compareImages(browser, historical, actual, sample.regions);
      assert.deepEqual(strictFailures(comparison), [], `${sample.id}: historical pixel regions differ`);
      // Committed previews must reproduce current geometry. Human-review text
      // remains in the unmasked diff but does not impose a host font renderer.
      const preview = await compareImages(browser, readReference(`rendered/${sample.id}.png`), actual, sample.regions);
      assert.deepEqual(strictFailures(preview), [], `${sample.id}: committed preview geometry is stale`);
    }
  });

  it('keeps historical text height and baseline placement within 3px and leaves normal labels unclipped', async t => {
    const cases = [
      {
        id: 'appearance-active',
        name: 'Appearance title',
        region: { x: 192, y: 3, width: 96, height: 16 }
      },
      {
        id: 'finder-active',
        name: 'Finder info',
        region: { x: 135, y: 25, width: 150, height: 15 }
      },
      {
        id: 'date-time-active',
        name: 'Date & Time title',
        region: { x: 148, y: 3, width: 80, height: 15 }
      }
    ];
    for (const entry of cases) {
      const sample = manifest.samples.find(sample => sample.id === entry.id);
      const original = await textInk(browser, readReference(`original/${entry.id}.png`), entry.region);
      const frameInk = await textInk(browser, readReference(`capture/${entry.id}.png`), {
        ...entry.region,
        x: sample.crop[0] + entry.region.x,
        y: sample.crop[1] + entry.region.y
      });
      assert.deepEqual(frameInk, original, `${entry.name}: text region must come from the raw guest frame`);
      const livePNG = await captureSample(browser, sample);
      const live = await textInk(browser, livePNG, entry.region);
      assert.ok(original.count > 40 && live.count > 40, `${entry.name}: readable ink must exist`);
      assert.ok(Math.abs(live.height - original.height) <= 3,
        `${entry.name}: ink height ${live.height}px versus historical ${original.height}px`);
      assert.ok(Math.abs(live.center - original.center) <= 3,
        `${entry.name}: vertical ink center moved by more than 3px`);
      assert.ok(Math.abs(live.centerX - original.centerX) <= 3,
        `${entry.name}: centered text moved horizontally by more than 3px`);
      // The fallback font has narrower letters. Keep each line's overall footprint.
      assert.ok(Math.abs(live.width - original.width) <= original.width * 0.12,
        `${entry.name}: ink width ${live.width}px versus historical ${original.width}px`);
      t.diagnostic(`${entry.name}: historical height/center ${original.height}/${original.center}; live ${live.height}/${live.center}`);

      if (entry.id === 'appearance-active') {
        const displacedPNG = await captureSample(browser, sample, page => {
          return page.addStyleTag({ content: '.caption { transform: translateY(6px) !important; }' });
        });
        const displaced = await textInk(browser, displacedPNG, entry.region);
        assert.ok(Math.abs(displaced.center - original.center) > 3
            || Math.abs(displaced.height - original.height) > 3,
          'Text-placement negative control must reject a 6px title displacement');
      }

      await captureSample(browser, sample, async page => {
        const failures = await page.evaluate(() => {
          const selectors = '.caption, .reference-finder-info, .reference-setting-label, .reference-setting-hint, .reference-popup-value, .reference-dt-label';
          const failures = [];
          for (const element of document.querySelectorAll(selectors)) {
            const range = document.createRange();
            range.selectNodeContents(element);
            const text = range.getBoundingClientRect();
            if (!text.width || !text.height) failures.push(`${element.className}: missing visible text box`);
            if (element.scrollWidth > element.clientWidth + 1 && element.clientWidth > 0) {
              failures.push(`${element.className}: horizontal text overflow`);
            }
            for (let ancestor = element; ancestor; ancestor = ancestor.parentElement) {
              const style = getComputedStyle(ancestor);
              const box = ancestor.getBoundingClientRect();
              if (['hidden', 'clip', 'scroll', 'auto'].includes(style.overflowX)
                  && (text.left < box.left - 1 || text.right > box.right + 1)) {
                failures.push(`${element.className}: clipped horizontally by ${ancestor.className || ancestor.id}`);
              }
              if (['hidden', 'clip', 'scroll', 'auto'].includes(style.overflowY)
                  && (text.top < box.top - 2 || text.bottom > box.bottom + 2)) {
                failures.push(`${element.className}: clipped vertically by ${ancestor.className || ancestor.id}`);
              }
            }
          }
          return failures;
        });
        assert.deepEqual(failures, [], `${entry.name}: normal-width captions and settings must remain readable`);
      });
    }
  });

  it('rejects a deliberate one-pixel live close-control displacement by name', async () => {
    const sample = manifest.samples.find(sample => {
      return sample.state === 'active' && sample.regions.some(region => {
        return /close/i.test(region.name) && region.mode !== 'review';
      });
    });
    assert.ok(sample, 'Need an active historical sample with a named close-control region');
    const shifted = await captureSample(browser, sample, page => {
      return page.addStyleTag({
        content: '#specimen .pt-tbox-close { transform: translateX(1px) !important; }'
      });
    });
    const report = await compareImages(browser, readReference(`original/${sample.id}.png`), shifted, sample.regions);
    assert.ok(strictFailures(report).some(region => /close/i.test(region.name)), 'Negative control failed: the named close-control check must detect +1px');
  });

  it('rejects regressions to shared .pt-groupbox legend groove masking and .pt-btn:disabled flat state on Date & Time', async () => {
    const dtSample = manifest.samples.find(sample => sample.id === 'date-time-active');
    assert.ok(dtSample, 'Need date-time-active sample');

    const unmaskedLegend = await captureSample(browser, dtSample, page => {
      return page.addStyleTag({ content: '.pt-groupbox > legend { background: transparent !important; }' });
    });
    const legendReport = await compareImages(browser, readReference('original/date-time-active.png'), unmaskedLegend, dtSample.regions);
    assert.ok(
      strictFailures(legendReport).some(r => /legend masked groove/i.test(r.name)),
      'Closed-loop negative control failed: transparent .pt-groupbox > legend must fail legend masked groove check'
    );

    const beveledDisabled = await captureSample(browser, dtSample, page => {
      return page.addStyleTag({ content: '.pt-btn:disabled { box-shadow: inset 1px 1px 0 #fff, inset -1px -1px 0 #777 !important; }' });
    });
    const disabledReport = await compareImages(browser, readReference('original/date-time-active.png'), beveledDisabled, dtSample.regions);
    assert.ok(
      strictFailures(disabledReport).some(r => /Disabled Server Options/i.test(r.name)),
      'Closed-loop negative control failed: beveled .pt-btn:disabled must fail Disabled Server Options check'
    );
  });

  it('opens both native file and Pages-style paths with a persistent Chinese locale', async () => {
    const server = createServer(async (request, response) => {
      try {
        const path = new URL(request.url, 'http://localhost').pathname;
        if (path !== '/platinum-ui/dist/platinum.css'
            && !/^\/platinum-ui\/gallery\/reference\/[a-zA-Z0-9_./-]+$/.test(path)) {
          response.writeHead(404).end();
          return;
        }
        const target = new URL('../' + path.slice('/platinum-ui/'.length), import.meta.url);
        const data = await readFile(target);
        const extension = target.pathname.split('.').at(-1);
        const contentTypes = { html: 'text/html', js: 'text/javascript', css: 'text/css' };
        response.setHeader('Content-Type', contentTypes[extension] ?? 'image/png');
        response.end(data);
      } catch {
        response.writeHead(404).end();
      }
    });
    await new Promise((resolve, reject) => {
      server.once('error', reject);
      server.listen(0, '127.0.0.1', resolve);
    });
    const page = await browser.newPage();
    try {
      const pagesURL = `http://127.0.0.1:${server.address().port}/platinum-ui/gallery/reference/index.html`;
      for (const base of [new URL('index.html', referenceRoot).href, pagesURL]) {
        await page.goto(base + '?lang=zh-CN');
        assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN');
        assert.equal(await page.locator('#samples article').count(), 1);
        assert.equal(await page.locator('#sample-select option').count(), manifest.samples.length);
        await page.locator('#sample-select').focus();
        await page.keyboard.press('Space');
        await page.keyboard.press('ArrowDown');
        await page.keyboard.press('Escape');
        assert.equal(await page.locator('#sample-select').inputValue(), '0');
        await page.keyboard.press('Space');
        await page.keyboard.press('ArrowDown');
        await page.keyboard.press('Enter');
        assert.equal(new URL(page.url()).searchParams.get('id'), manifest.samples[1].id);
        await page.getByRole('button', { name: '上一项', exact: true }).click();
        assert.equal(new URL(page.url()).searchParams.get('id'), manifest.samples[0].id);
        await page.getByRole('button', { name: '实时实现', exact: true }).click();
        assert.equal(await page.locator('iframe').count(), 1);
        await page.getByRole('button', { name: '叠加对照', exact: true }).click();
        await page.locator('#opacity').focus();
        await page.keyboard.press('ArrowRight');
        assert.equal(await page.locator('#opacity').inputValue(), '51');
        assert.equal(await page.locator('.overlay-image').evaluate(image => image.style.opacity), '0.51');
        assert.equal(await page.locator('a[href^="capture/"]').count(), 1);
        assert.equal(await page.locator('a[href^="rendered/"]').count(), 1);
        await page.getByRole('button', { name: '完整差分 ×4', exact: true }).click();
        for (const image of await page.locator('.stage img').all()) {
          await image.evaluate(image => image.decode());
          assert.ok(await image.evaluate(image => image.naturalWidth > 0));
        }
        await page.getByRole('button', { name: 'English', exact: true }).click();
        assert.equal(new URL(page.url()).searchParams.has('lang'), false);
        await page.getByRole('button', { name: '中文', exact: true }).click();
        assert.equal(new URL(page.url()).searchParams.get('lang'), 'zh-CN');
        await page.locator('#opacity').evaluate(input => {
          input.value = '50';
          input.dispatchEvent(new Event('input'));
        });
        await page.reload();
        assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN');
      }

      // Malformed manifest ({} / { samples: null }) must degrade cleanly with zero uncaught errors and disabled controls
      for (const payload of ['window.PLATINUM_REFERENCE = {};', 'window.PLATINUM_REFERENCE = { samples: null };']) {
        const badPage = await browser.newPage();
        const pageErrors = [];
        badPage.on('pageerror', err => pageErrors.push(err.message));
        await badPage.route('**/samples.js', route => route.fulfill({ contentType: 'text/javascript', body: payload }));
        await badPage.goto(pagesURL);
        assert.deepEqual(pageErrors, []);
        assert.equal(await badPage.locator('#next').isDisabled(), true);
        assert.equal(await badPage.locator('#previous').isDisabled(), true);
        assert.equal(await badPage.locator('#sample-select').isDisabled(), true);
        await badPage.close();
      }
    } finally {
      await page.close();
      await new Promise(resolve => server.close(resolve));
    }
  });
});
