#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolvePlaywright } from '../bin/platinum-check.mjs';
import { referenceRoot, loadSamples, captureSample, compareImages, readReference, sourceDigest, sha256, strictFailures } from './reference-lib.mjs';

export async function generateReferenceShots() {
  const manifest = loadSamples();
  const playwright = resolvePlaywright();
  if (!playwright) throw new Error('Reference previews require Playwright. Set PLAYWRIGHT_MODULE_PATH to an installed module.');
  // This local plain-script mirror deliberately works under file:// without fetch.
  const mirror = '// Generated by scripts/reference-shots.mjs; source: samples.json\n'
    + `window.PLATINUM_REFERENCE = ${readReference('samples.json').toString().trimEnd()};\n`;
  writeFileSync(new URL('samples.js', referenceRoot), mirror);
  const browser = await playwright.chromium.launch({ ignoreDefaultArgs: ['--hide-scrollbars'] });
  try {
    for (const dir of ['rendered/', 'difference/']) mkdirSync(new URL(dir, referenceRoot), { recursive: true });
    const reports = [];
    const failures = [];
    for (const sample of manifest.samples) {
      const actual = await captureSample(browser, sample);
      const report = await compareImages(browser, readReference(`original/${sample.id}.png`), actual, sample.regions);
      for (const region of strictFailures(report)) {
        failures.push(`${sample.id} / ${region.name}: ${region.changed} pixels differ`);
      }
      writeFileSync(new URL(`rendered/${sample.id}.png`, referenceRoot), actual);
      writeFileSync(new URL(`difference/${sample.id}.png`, referenceRoot), Buffer.from(report.png, 'base64'));
      const { png, ...metrics } = report;
      reports.push({
        id: sample.id,
        ...metrics,
        hashes: {
          original: sha256(readReference(`original/${sample.id}.png`)),
          rendered: sha256(actual),
          difference: sha256(Buffer.from(report.png, 'base64')),
          capture: sha256(readReference(`capture/${sample.id}.png`))
        }
      });
      console.log(`${sample.id}: ${report.changed}/${report.pixels} historical pixels differ`);
    }
    writeFileSync(new URL('previews.json', referenceRoot), JSON.stringify({ sourceDigest: sourceDigest(), reports }, null, 2) + '\n');
    if (failures.length) throw new Error('Historical geometry differs:\n' + failures.join('\n'));
  } finally { await browser.close(); }
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  generateReferenceShots().catch(error => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
